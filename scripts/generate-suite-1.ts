/**
 * Builds Suite 1 (squares & rectangles): 200 levels growing from 4×4 to 40×40, in tiers.
 * Run with `npm run levels:suite-1`. Output is deterministic for a given generator version.
 */
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { toLevelFile } from '../src/generator/export';
import { generateLevel, type GeneratedLevel } from '../src/generator/generator';
import { fullMask } from '../src/generator/shapes';

const SUITE_ID = 1;
/** Each tier spreads its levels from a minSide square up to a maxSide square. */
const TIERS: Tier[] = [
  { levelCount: 100, minSide: 4, maxSide: 20 },
  { levelCount: 100, minSide: 21, maxSide: 40 },
];
/** Portrait rectangles: height = width + extra. */
const HEIGHT_EXTRAS = [0, 1, 2];
const SEEDS_PER_LEVEL = 16;
const TURN_CHANCE = 0.35;
/** Arrow length range as multiples of the board's shorter side. */
const MAX_LENGTH_FACTOR = 1.25;
const MIN_LENGTH_FACTOR = 0.5;

const OUT_DIR = join(__dirname, '..', 'src', 'levels', 'suites', `suite-${SUITE_ID}`);

interface Tier {
  levelCount: number;
  minSide: number;
  maxSide: number;
}

interface Size {
  width: number;
  height: number;
}

function boardSizes(tier: Tier): Size[] {
  const sizes: Size[] = [];
  for (let width = tier.minSide; width <= tier.maxSide; width++) {
    for (const extra of HEIGHT_EXTRAS) {
      const height = width + extra;
      if (height <= tier.maxSide) sizes.push({ width, height });
    }
  }
  return sizes.sort((a, b) => a.width * a.height - b.width * b.height || a.width - b.width);
}

/** Spread each tier's levels evenly over its size list, from its smallest square to its largest. */
function levelSizes(): Size[] {
  return TIERS.flatMap((tier) => {
    const sizes = boardSizes(tier);
    return Array.from({ length: tier.levelCount }, (_, i) =>
      sizes[Math.round((i * (sizes.length - 1)) / (tier.levelCount - 1))],
    );
  });
}

/** Prefer full coverage, then deeper clearing order, then fewer arrows free at the start. */
function score(gen: GeneratedLevel): number {
  const { coverage, solveDepth, initialAvailable } = gen.stats;
  return coverage * 1000 + solveDepth - initialAvailable * 0.5;
}

function hintQuota(size: Size): number {
  return Math.min(5, 2 + Math.floor(Math.min(size.width, size.height) / 5));
}

function levelName(size: Size): string {
  const kind = size.width === size.height ? 'Square' : 'Rectangle';
  return `${kind} ${size.width}×${size.height}`;
}

function fileName(level: number): string {
  return `level-${String(level).padStart(3, '0')}.json`;
}

function main() {
  mkdirSync(OUT_DIR, { recursive: true });
  for (const f of readdirSync(OUT_DIR)) {
    if (f.endsWith('.json')) rmSync(join(OUT_DIR, f));
  }

  const files: string[] = [];
  levelSizes().forEach((size, i) => {
    const level = i + 1;
    const side = Math.min(size.width, size.height);
    const maxLength = Math.round(side * MAX_LENGTH_FACTOR);
    const minLength = Math.max(2, Math.round(side * MIN_LENGTH_FACTOR));

    let best: GeneratedLevel | null = null;
    for (let k = 0; k < SEEDS_PER_LEVEL; k++) {
      const gen = generateLevel({
        ...size,
        mask: fullMask(size.width, size.height),
        seed: SUITE_ID * 1_000_000 + level * 1_000 + k,
        minLength,
        maxLength,
        turnChance: TURN_CHANCE,
      });
      if (!best || score(gen) > score(best)) best = gen;
    }

    const file = {
      suite: SUITE_ID,
      ...toLevelFile(best!, {
        level,
        name: levelName(size),
        hintQuota: hintQuota(size),
        shape: 'rectangle',
        minLength,
        maxLength,
        turnChance: TURN_CHANCE,
      }),
    };
    const name = fileName(level);
    writeFileSync(join(OUT_DIR, name), `${JSON.stringify(file, null, 2)}\n`);
    files.push(name);

    const s = best!.stats;
    console.log(
      `${name}  ${size.width}x${size.height}  arrows=${s.arrowCount}  coverage=${(s.coverage * 100).toFixed(1)}%  depth=${s.solveDepth}  free=${s.initialAvailable}  longest=${Math.max(...best!.arrows.map((a) => a.length))}`,
    );
  });

  const imports = files.map((f, i) => `import l${i + 1} from './${f}';`).join('\n');
  const list = files.map((_, i) => `  l${i + 1},`).join('\n');
  writeFileSync(
    join(OUT_DIR, 'index.ts'),
    `/* Generated by scripts/generate-suite-1.ts — do not edit by hand. */\n` +
      `import type { LevelFile } from '../../../game/types';\n${imports}\n\n` +
      `export const SUITE_1_LEVELS = [\n${list}\n] as LevelFile[];\n`,
  );
}

main();
